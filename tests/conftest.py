def compute_file_hash(path: Path) -> str:
    """Calculate SHA256 checksum for a file."""
    hasher = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(65536):
            hasher.update(chunk)
    return hasher.hexdigest()
